def confirmatory(p9: dict) -> None:
    fs = "_fs-aitw_frozen_v1"

    # ---- descriptive test means ----
    pats = {
        "A (flat)": f"variantA_seed4[234]_n1200_*mix-all_with_coords{fs}.json",
        "B (aux loss)": f"variantB_seed4[234]_n1200_*aux1.0{fs}.json",
        "C (hard routing)": f"variantC_seed4[234]_n1200_*mix-all_with_coords{fs}.json",
        "D-hook (additive)": f"Dhook_seed4[234]_n1200_*init0.0{fs}.json",
        "D-token (prepended)": f"Dtoken_seed4[234]_n1200_*init0.02_causal{fs}.json",
    }
    stats = {}
    for nm, pat in pats.items():
        files = sorted(glob.glob(str(P4 / pat)))
        if len(files) != 3:
            print(f"[p10] WARNING: {nm}: {len(files)} test runs found (expected 3)")
        if files:
            stats[nm] = {
                "hit010": seed_stats(files, "test", "hit_at_010"),
                "hit025": seed_stats(files, "test", "hit_at_025"),
                "l2": seed_stats(files, "test", "mean_normalized_l2"),
                "parse": seed_stats(files, "test", "parse_rate"),
            }
    pri = p9["primary"]
    cmap = {"B (aux loss)": ("P1_B_vs_A", False), "D-hook (additive)": ("P2_Dhook_vs_A", False),
            "C (hard routing)": ("C_vs_A", True), "D-token (prepended)": ("Dtoken_vs_A", True)}
    L = [r"\begin{tabular}{lccccc}", r"\toprule",
         r"variant & hit@0.10 & L2 $\downarrow$ & parse & $\Delta$ vs.\ A [95\% CI] & $p$ (Holm) \\",
         r"\midrule"]
    for nm in pats:
        if nm not in stats:
            continue
        m10, s10, _ = stats[nm]["hit010"]
        l2, _, _ = stats[nm]["l2"]
        pr, _, _ = stats[nm]["parse"]
        prs = f"${100*pr:.1f}\\%$"
        if nm in cmap:
            key, secondary = cmap[nm]
            src = p9["secondary"] if secondary else p9["primary"]
            r = src[key]["metrics"]["hit_at_010"]["episode_clustered"]
            hp = src[key].get("holm_adjusted_p_hit010")
            censored = r["p_value"] <= r["p_resolution"]
            holm = "" if secondary else (
                f" ($\\leq${hp:.2g})" if censored else f" ({hp:.3g})")
            L.append(f"{nm} & ${m10:.3f} \\pm {s10:.3f}$ & ${l2:.3f}$ & {prs} & {ci(r)} & {fmt_p(r)}{holm} \\\\")
        else:
            L.append(f"{nm} & ${m10:.3f} \\pm {s10:.3f}$ & ${l2:.3f}$ & {prs} & --- & --- \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("tab_confirmatory_main.tex", L)

    for mk, key in [("ConfBvsA", "P1_B_vs_A"), ("ConfDhvsA", "P2_Dhook_vs_A"),
                    ("ConfDtvsB", "P3_Dtoken_vs_B"), ("ConfEtoEvsA", "P4_e2e_pred_vs_A")]:
        r = pri[key]["metrics"]["hit_at_010"]["episode_clustered"]
        macro(mk, ci(r))
        macro(mk + "p", p_inline(r))
        _hp = pri[key]["holm_adjusted_p_hit010"]
        macro(mk + "Holm", (f"{{\\leq}}{_hp:.2g}"
                            if r["p_value"] <= r["p_resolution"] else f"{_hp:.3g}"))
        rl = pri[key]["metrics"]["mean_normalized_l2"]["episode_clustered"]
        macro(mk + "Ltwo", ci(rl))
        macro(mk + "Ltwop", p_inline(rl))

    if "A (flat)" in stats:
        m10, s10, seeds = stats["A (flat)"]["hit010"]
        macro("ConfAhit", f"{m10:.3f} \\pm {s10:.3f}")
        pr, _, _ = stats["A (flat)"]["parse"]
        macro("ConfAparse", f"{100*pr:.1f}\\%")
    if "B (aux loss)" in stats:
        m10, s10, _ = stats["B (aux loss)"]["hit010"]
        macro("ConfBhit", f"{m10:.3f} \\pm {s10:.3f}")

    # ---- control ----
    rows = []
    for nm, pat, key in [
        ("A (flat)", f"variantA_seed4[234]_n1000_*mix-taps_and_swipes{fs}.json", None),
        ("B (aux loss)", f"variantB_seed4[234]_n1000_*taps_and_swipes_aux1.0{fs}.json", "control_B_vs_A"),
        ("C (hard routing)", f"variantC_seed4[234]_n1000_*mix-taps_and_swipes{fs}.json", "control_C_vs_A"),
        ("D-hook (additive)", f"Dhook_seed4[234]_n1000_*taps_and_swipes_init0.0{fs}.json", "control_Dhook_vs_A"),
    ]:
        files = sorted(glob.glob(str(P4 / pat)))
        if not files:
            continue
        m10, s10, _ = seed_stats(files, "test", "hit_at_010")
        l2, _, _ = seed_stats(files, "test", "mean_normalized_l2")
        pr, _, _ = seed_stats(files, "test", "parse_rate")
        prs = f"${100*pr:.1f}\\%$"
        if key and key in p9["secondary"]:
            r = p9["secondary"][key]["metrics"]["hit_at_010"]["episode_clustered"]
            rows.append(f"{nm} & ${m10:.3f} \\pm {s10:.3f}$ & ${l2:.3f}$ & {prs} & {ci(r)} & {fmt_p(r)} \\\\")
        else:
            rows.append(f"{nm} & ${m10:.3f} \\pm {s10:.3f}$ & ${l2:.3f}$ & {prs} & --- & --- \\\\")
    if rows:
        L = [r"\begin{tabular}{lccccc}", r"\toprule",
             r"variant & hit@0.10 & L2 $\downarrow$ & parse & $\Delta$ vs.\ A [95\% CI] & $p$ \\",
             r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}"]
        write("tab_control.tex", L)

    # ---- low-data grid ----
    rows = []
    for n in (300, 500, 800):
        cols = [f"$n{{=}}{n}$"]
        fa = sorted(glob.glob(str(P4 / f"variantA_seed4[234]_n{n}_*mix-all_with_coords{fs}.json")))
        if not fa:
            continue
        ma, _, _ = seed_stats(fa, "test", "hit_at_010")
        cols.append(f"${ma:.3f}$")
        for vk, ck in [("variantB", f"lowdata{n}_B_vs_A"), ("Dhook", f"lowdata{n}_Dhook_vs_A")]:
            if ck in p9["secondary"]:
                r = p9["secondary"][ck]["metrics"]["hit_at_010"]["episode_clustered"]
                cols.append(ci(r))
            else:
                cols.append("---")
        rows.append(" & ".join(cols) + r" \\")
    if rows:
        L = [r"\begin{tabular}{lccc}", r"\toprule",
             r"$n_{\text{train}}$ & A & $\Delta$ B$-$A [95\% CI] & $\Delta$ D-hook$-$A [95\% CI] \\",
             r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}"]
        write("tab_lowdata.tex", L)

    # ---- confirmatory per-class decomposition (seed-averaged, test) ----
    # AITW string label -> canonical class used in the paper's per-class table.
    _CLS = {"tap": "click", "type": "type", "swipe_up": "scroll",
            "swipe_down": "scroll", "swipe_left": "scroll", "swipe_right": "scroll"}

    def per_class_means(pat: str) -> dict:
        """Per-class hit@0.10 computed from per_example_dist grouped by the
        frozen split's own step labels, so parse failures are sentinel-scored
        and counted as misses — the paper's declared convention. The run
        JSONs' `per_class` block uses parsed-only denominators (audit finding:
        C's 3.8% test parse failures inflated its per-class scroll rate), so
        it must not feed paper tables."""
        acc: dict[str, list[float]] = {}
        ns: dict[str, int] = {}
        for f in sorted(glob.glob(str(P4 / pat))):
            d = json.loads(Path(f).read_text())
            dist = np.asarray(d["final_test_metrics"]["per_example_dist"], dtype=np.float64)
            labels = [_CLS[k["label"]] for k in d["test_step_keys"]]
            assert len(labels) == dist.shape[0], f"{f}: keys/dist length mismatch"
            for cls in sorted(set(labels)):
                mask = np.array([l == cls for l in labels])
                acc.setdefault(cls, []).append(float((dist[mask] <= 0.10).mean()))
                ns[cls] = int(mask.sum())
        return {c: (float(np.mean(vs)), ns[c]) for c, vs in acc.items()}

    pc_rows = {nm: per_class_means(pat) for nm, pat in pats.items()}
    if pc_rows.get("A (flat)"):
        classes = [c for c in ("click", "scroll", "type") if c in pc_rows["A (flat)"]]
        head = " & ".join(f"{c} ($n{{=}}{pc_rows['A (flat)'][c][1]}$)" for c in classes)
        L = [r"\begin{tabular}{l" + "c" * len(classes) + "}", r"\toprule",
             f"variant & {head} \\\\", r"\midrule"]
        for nm in pats:
            if nm not in pc_rows or not pc_rows[nm]:
                continue
            cells = []
            for c in classes:
                v = pc_rows[nm].get(c)
                cells.append(f"${v[0]:.3f}$" if v else "---")
            L.append(f"{nm} & " + " & ".join(cells) + r" \\")
        L += [r"\bottomrule", r"\end{tabular}"]
        write("tab_confirmatory_perclass.tex", L)
        a_pc, dh_pc = pc_rows["A (flat)"], pc_rows.get("D-hook (additive)", {})
        if "scroll" in a_pc and "scroll" in dh_pc:
            macro("ConfAscroll", f"{a_pc['scroll'][0]:.3f}")
            macro("ConfDhscroll", f"{dh_pc['scroll'][0]:.3f}")
            macro("ConfScrollDelta", f"{dh_pc['scroll'][0] - a_pc['scroll'][0]:+.3f}")
        if "click" in a_pc and "click" in dh_pc:
            macro("ConfAclick", f"{a_pc['click'][0]:.3f}")
            macro("ConfDhclick", f"{dh_pc['click'][0]:.3f}")
            macro("ConfClickDelta", f"{dh_pc['click'][0] - a_pc['click'][0]:+.3f}")
        # Absolute share of the aggregate gain each class supplies. The
        # proportional (fold) effect is largest on scroll, but click is 3x
        # more frequent, so click still supplies most of the absolute gain —
        # the text must not claim the gain "concentrates in scroll".
        if a_pc.get("click") and a_pc.get("scroll") and dh_pc:
            c_abs = a_pc["click"][1] * (dh_pc["click"][0] - a_pc["click"][0])
            s_abs = a_pc["scroll"][1] * (dh_pc["scroll"][0] - a_pc["scroll"][0])
            macro("ConfClickAbsShare", f"{100 * c_abs / (c_abs + s_abs):.0f}\\%")
            macro("ConfScrollAbsShare", f"{100 * s_abs / (c_abs + s_abs):.0f}\\%")
        # Relative (fold) improvements, so the text never hand-types a ratio.
        if a_pc.get("scroll", (0,))[0]:
            macro("ConfScrollFold", f"{dh_pc['scroll'][0] / a_pc['scroll'][0]:.1f}")
        if a_pc.get("click", (0,))[0]:
            macro("ConfClickFold", f"{dh_pc['click'][0] / a_pc['click'][0]:.1f}")

    # ---- e2e on test ----
    e2f = sorted(glob.glob(str(P4 / f"e2e_seed4[234]_n1200_*mix-all_with_coords{fs}.json")))
    if e2f:
        po, pp, s1a = [], [], []
        for f in e2f:
            d = json.loads(Path(f).read_text())
            tb = d["final_test_metrics"]
            po.append(_metric_from_ped(tb["oracle_metrics"]["per_example_dist"], "hit_at_010"))
            pp.append(_metric_from_ped(tb["predicted_metrics"]["per_example_dist"], "hit_at_010"))
            s1a.append(tb["stage1_test_acc"])
        macro("ConfEtoEOracle", f"{np.mean(po):.3f} \\pm {np.std(po, ddof=1):.3f}")
        macro("ConfEtoEPred", f"{np.mean(pp):.3f} \\pm {np.std(pp, ddof=1):.3f}")
        macro("ConfStageOneAcc", f"{np.mean(s1a):.3f}")
        rg = p9["secondary"]["e2e_pred_vs_oracle"]["metrics"]["hit_at_010"]["episode_clustered"]
        macro("ConfEtoEGap", ci(rg))
        macro("ConfEtoEGapp", p_inline(rg))
        # Share of the e2e oracle arm's advantage over A that Stage-1 error
        # absorbs. Reported descriptively (no new significance test) so the
        # text never overstates the gap relative to the oracle advantage.
        a_hit, _, _ = seed_stats(
            sorted(glob.glob(str(P4 / f"variantA_seed4[234]_n1200_*mix-all_with_coords{fs}.json"))),
            "test", "hit_at_010")
        oracle_adv = float(np.mean(po)) - a_hit
        macro("ConfEtoEOracleAdv", f"{oracle_adv:+.3f}")
        macro("ConfEtoEGapShare", f"{100 * abs(rg['delta']) / oracle_adv:.0f}\\%")
        # Stage-1 accuracy on the frozen val split vs the untouched test split:
        # the generalization drop that explains why the oracle gain does not
        # survive the real classifier.
        s1v = [json.loads(Path(f).read_text())["stage1_val_acc"] for f in e2f]
        macro("ConfStageOneValAcc", f"{np.mean(s1v):.3f}")
    for nm, key in [("ConfCvsA", "C_vs_A"), ("ConfDtvsA", "Dtoken_vs_A"),
                    ("ConfDhvsB", "Dhook_vs_B"),
                    ("ConfCtrlDhvsA", "control_Dhook_vs_A"),
                    ("ConfCtrlBvsA", "control_B_vs_A"),
                    ("ConfCtrlCvsA", "control_C_vs_A")]:
        if key in p9["secondary"]:
            rr = p9["secondary"][key]["metrics"]["hit_at_010"]["episode_clustered"]
            macro(nm, ci(rr))
            macro(nm + "p", p_inline(rr))


