MACROS: dict[str, str] = {}

_CLS_HIST = {"tap": "click", "type": "type", "swipe_up": "scroll",
             "swipe_down": "scroll", "swipe_left": "scroll", "swipe_right": "scroll"}


def macro(name: str, value: str) -> None:
    assert name.isalpha(), f"macro names must be alphabetic: {name}"
    MACROS[name] = value


def fmt_p(r: dict) -> str:
    """Table cell: math-mode p-value, floored at Monte Carlo resolution."""
    p, res = r["p_value"], r["p_resolution"]
    return f"$<10^{{{_mag(res)}}}$" if p <= res else f"${p:.3g}$"


def _mag(x: float) -> int:
    """Ceiling power of ten, e.g. 9.999e-05 -> -4."""
    import math
    return int(math.ceil(math.log10(x)))


def p_inline(r: dict) -> str:
    """Inline macro body for use inside an existing `$p=...$`: no delimiters,
    and never claims more precision than the permutation budget supports."""
    p, res = r["p_value"], r["p_resolution"]
    return f"{p:.3g}" if p > res else f"{{<}}10^{{{_mag(res)}}}"


def ci(r: dict, digits: int = 3) -> str:
    d = f"{{:+.{digits}f}}"
    return (f"${d.format(r['delta'])}$ "
            f"[{d.format(r['ci_low'])}, {d.format(r['ci_high'])}]")


def _metric_from_ped(ped: list[float], key: str) -> float:
    """Metric from per-example distances with parse failures ALREADY scored at
    the sqrt(2) sentinel — the paper's declared convention (misses counted).
    The run JSONs' headline hit/L2 fields use a parsed-only denominator and
    must never feed paper tables (audit finding: C's parse_rate < 1 made its
    raw headline numbers inconsistent with the reanalysis + delta columns)."""
    a = np.asarray(ped, dtype=np.float64)
    if key == "mean_normalized_l2":
        return float(a.mean())
    r = {"hit_at_005": 0.05, "hit_at_010": 0.10, "hit_at_025": 0.25}[key]
    return float((a <= r).mean())


def seed_stats(files: list[str], which: str, key: str) -> tuple[float, float, list[float]]:
    vals = []
    for f in files:
        d = json.loads(Path(f).read_text())
        m = d["final_test_metrics"] if which == "test" else d["final_val_metrics"]
        vals.append(m[key] if key == "parse_rate" else _metric_from_ped(m["per_example_dist"], key))
    a = np.asarray(vals, dtype=np.float64)
    return float(a.mean()), float(a.std(ddof=1)), [float(v) for v in a]


def hist_stats(pattern: str, key: str) -> tuple[float, float]:
    vals = []
    for f in sorted(glob.glob(str(P4 / pattern))):
        d = json.loads(Path(f).read_text())
        vals.append(_metric_from_ped(d["final_val_metrics"]["per_example_dist"], key))
    a = np.asarray(vals, dtype=np.float64)
    return float(a.mean()), float(a.std(ddof=1))


def write(name: str, lines: list[str]) -> None:
    TABDIR.mkdir(exist_ok=True)
    (TABDIR / name).write_text("% AUTO-GENERATED by scripts/p10_render_paper_tables.py — do not edit\n"
                               + "\n".join(lines) + "\n")
    print(f"[p10] wrote tables/{name}")


